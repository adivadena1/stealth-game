// Ember Vault — the three heists.
// Each level is a grid of characters, one row per string, 30 columns by 20
// rows. Legend:
//   # wall            C crate (cover: blocks movement and sight)
//   . floor           B bookshelf (tall cover: blocks movement and sight)
//   d dark floor      L lamp (a pool of light; being seen in it is worse)
//   P player start    X exit door (reach it unseen to finish the level)
//   * ember crystal  o pebble cache (+2 pebbles)
//   1..4 guard spawn points; their patrols are listed below each map.
// A guard's patrol is a loop of tile waypoints it walks between.

function checkMap(rows, name) {
  if (rows.length !== 20) throw new Error(name + ': expected 20 rows, got ' + rows.length);
  for (let i = 0; i < rows.length; i += 1) {
    if (rows[i].length !== 30) throw new Error(name + ' row ' + i + ': ' + rows[i].length + ' chars');
  }
}

